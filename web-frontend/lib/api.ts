export function getCropImageUrl(cropName: string): string {
  const cropLower = cropName.toLowerCase();
  if (cropLower.includes('tomato')) return '/images/products/tomato.jpg';
  if (cropLower.includes('capsicum') || cropLower.includes('bell pepper')) return '/images/products/capsicum.jpg';
  if (cropLower.includes('spinach') || cropLower.includes('palak') || cropLower.includes('coriander') || cropLower.includes('fenugreek') || cropLower.includes('methi')) return '/images/products/spinach.jpg';
  if (cropLower.includes('brinjal') || cropLower.includes('eggplant')) return '/images/products/brinjal.jpg';
  if (cropLower.includes('cauliflower')) return '/images/products/cauliflower.jpg';
  if (cropLower.includes('cabbage')) return '/images/products/cabbage.jpg';
  if (cropLower.includes('bottle') || cropLower.includes('sorakaya') || cropLower.includes('ridge')) return '/images/products/bottle_gourd.jpg';
  if (cropLower.includes('bitter') || cropLower.includes('kakarakaya')) return '/images/products/bitter_gourd.jpg';
  if (cropLower.includes('cucumber') || cropLower.includes('dosakaya')) return '/images/products/cucumber.jpg';
  if (cropLower.includes('ginger') || cropLower.includes('allam')) return '/images/products/ginger.jpg';
  if (cropLower.includes('garlic')) return '/images/products/garlic.jpg';
  if (cropLower.includes('bean') || cropLower.includes('drumstick')) return '/images/products/green_beans.jpg';
  if (cropLower.includes('lady') || cropLower.includes('bhendi') || cropLower.includes('okra')) return '/images/products/lady_finger.jpg';
  if (cropLower.includes('chilli')) return '/images/products/green_chilli.jpg';
  if (cropLower.includes('onion')) return '/images/products/onion.jpg';
  if (cropLower.includes('carrot')) return '/images/products/carrot.jpg';
  if (cropLower.includes('potato')) return '/images/products/potato.jpg';
  return '/images/products/tomato.jpg';
}

